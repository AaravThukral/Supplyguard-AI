"""Train, evaluate, and serialize the SupplyGuard model suite."""
from __future__ import annotations

import json
from pathlib import Path

try:
    from .supplyguard_ml import choose_model, feature_importance, load_dataset, save_bundle, train_all
except ImportError:  # Supports `python src/train_model.py` as well as `python -m src.train_model`.
    from supplyguard_ml import choose_model, feature_importance, load_dataset, save_bundle, train_all


def _markdown_report(results: dict, selected: str, data, importance: list[dict]) -> str:
    lines = ["# Model Comparison Results", "", "Generated by `python -m src.train_model` from the local synthetic dataset.", "", f"**Selected model:** {selected}", "", "Selection prioritizes macro F1, then accuracy, with Logistic Regression as a deterministic tie-breaker.", "", "## Dataset and evaluation", "", f"- Records: {len(data):,}", f"- Features used: 17 (Supplier_ID excluded)", "- Split: 80/20 stratified hold-out, random state 42", "- Preprocessing: training-fitted ColumnTransformer with scaling and one-hot encoding", "", "## Model summary", "", "| Model | Accuracy | Macro F1 | Weighted F1 | Macro Precision | Macro Recall |", "|---|---:|---:|---:|---:|---:|"]
    for name, metrics in results.items():
        lines.append(f"| {name} | {metrics['accuracy']:.3f} | {metrics['macro_f1']:.3f} | {metrics['weighted_f1']:.3f} | {metrics['macro_precision']:.3f} | {metrics['macro_recall']:.3f} |")
    lines += ["", "## Detailed reports"]
    for name, metrics in results.items():
        lines += ["", f"### {name}", "", "| Class | Precision | Recall | F1 | Support |", "|---|---:|---:|---:|---:|"]
        for cls in ["Low", "Medium", "High"]:
            row = metrics["classification_report"][cls]
            lines.append(f"| {cls} | {row['precision']:.3f} | {row['recall']:.3f} | {row['f1-score']:.3f} | {int(row['support'])} |")
        lines += ["", f"Confusion matrix (Low, Medium, High): `{metrics['confusion_matrix']}`", f"Training time: `{metrics['training_seconds']:.4f}` seconds"]
    lines += ["", "## Selected-model global interpretation", "", "| Feature | Importance |", "|---|---:|"]
    lines += [f"| {item['feature']} | {item['importance']:.5f} |" for item in importance]
    lines += ["", "> Importance and contribution values describe model associations, not causal effects. The labels are synthetic and percentile-based; these metrics do not establish real-world supplier-risk accuracy.", ""]
    return "\n".join(lines)


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    data = load_dataset()
    fitted, results, *_ = train_all(data)
    selected = choose_model(results)
    artifact = root / "models" / "supplyguard_model.joblib"
    save_bundle(artifact, fitted[selected], selected, results)
    (root / "research" / "model_results").mkdir(parents=True, exist_ok=True)
    report = _markdown_report(results, selected, data, feature_importance(fitted[selected]))
    (root / "research" / "model_results" / "model_comparison.md").write_text(report, encoding="utf-8")
    (root / "research" / "model_results" / "metrics.json").write_text(json.dumps(results, indent=2), encoding="utf-8")
    print(report)
    print(f"\nSaved selected model to {artifact}")


if __name__ == "__main__":
    main()
